"""
MonitoringMetric model — time-series metrics for servers and databases.

Stores CPU, memory, disk, and network measurements at regular intervals.
In production, these would be collected by an agent; in demo mode,
they are generated by the seed script.
"""
from datetime import datetime
from sqlalchemy import String, Float, DateTime, ForeignKey, Index
from sqlalchemy.orm import Mapped, mapped_column, relationship

from app.database import Base


class MonitoringMetric(Base):
    __tablename__ = "monitoring_metrics"
    __table_args__ = (
        Index("ix_metrics_server_id", "server_id"),
        Index("ix_metrics_db_instance_id", "database_instance_id"),
        Index("ix_metrics_timestamp", "timestamp"),
        Index("ix_metrics_type", "metric_type"),
    )

    id: Mapped[int] = mapped_column(primary_key=True)

    # Which resource this metric belongs to (one of these should be set)
    server_id: Mapped[int | None] = mapped_column(ForeignKey("servers.id"), nullable=True)
    database_instance_id: Mapped[int | None] = mapped_column(
        ForeignKey("database_instances.id"), nullable=True
    )

    # Metric details
    metric_type: Mapped[str] = mapped_column(String(50), nullable=False)  # cpu, memory, disk, network, iops
    value: Mapped[float] = mapped_column(Float, nullable=False)
    unit: Mapped[str] = mapped_column(String(20), default="percent")     # percent, mbps, iops

    # Timestamp
    timestamp: Mapped[datetime] = mapped_column(DateTime(timezone=True), nullable=False, index=True)

    # Relationships
    server: Mapped["Server | None"] = relationship(back_populates="monitoring_metrics")
    database_instance: Mapped["DatabaseInstance | None"] = relationship(back_populates="monitoring_metrics")
